"""Controlled experiments: does a change actually help?

``compare_indices`` trains the full model twice, without and with the ENSO/IOD
features, under identical splits and grids, and reports validation (used for
the decision) and test (reported, not used to decide) side by side.
"""

from __future__ import annotations

import logging
import tempfile
from pathlib import Path

import pandas as pd

from . import config
from .evaluate import evaluate
from .features import INDEX_FEATURES
from .train import train

log = logging.getLogger(__name__)


def compare_indices(feat: pd.DataFrame, reports_dir: Path = config.REPORTS_DIR) -> dict:
    missing = [c for c in INDEX_FEATURES if c not in feat.columns]
    if missing:
        raise ValueError(f"features table lacks {missing}; rerun `climrisk features`")
    runs = {}
    with tempfile.TemporaryDirectory() as tmp:
        for label, use in (("Local predictors only", False), ("+ ENSO and IOD indices", True)):
            log.info("Experiment: %s", label)
            bundle = train(feat, use_indices=use)
            m = evaluate(bundle, feat, figures_dir=Path(tmp), reports_dir=Path(tmp),
                         make_figures=False)
            runs[label] = {"bundle": bundle, "metrics": m}

    (base_label, base), (idx_label, idx) = runs.items()

    def val_row(label, r):
        v = r["bundle"]["validation"]
        return (f"| {label} | {v['regression_mae_mm']['hgb']:.1f} | "
                f"{v['regression_mae_mm']['ridge']:.1f} | "
                f"{v['classification']['hgb']['log_loss']:.4f} | "
                f"{v['classification']['logistic']['log_loss']:.4f} |")

    def test_row(label, r):
        m = r["metrics"]
        reg, clf = m["regression"], m["classification"]
        lo, hi = reg["hgb"]["mae_skill_95ci"]
        return (f"| {label} | {reg['hgb']['mae_skill_vs_climatology']:+.1%} "
                f"[{lo:+.1%}, {hi:+.1%}] | "
                f"{reg['ridge']['mae_skill_vs_climatology']:+.1%} | "
                f"{clf['hgb']['brier_skill_vs_ensemble']:+.1%} | "
                f"{clf['logistic']['brier_skill_vs_ensemble']:+.1%} | "
                f"{m['interval']['empirical_coverage']:.1%} |")

    v_base = base["bundle"]["validation"]
    v_idx = idx["bundle"]["validation"]
    helps_reg = v_idx["regression_mae_mm"]["hgb"] < v_base["regression_mae_mm"]["hgb"]
    helps_clf = (v_idx["classification"]["hgb"]["log_loss"]
                 < v_base["classification"]["hgb"]["log_loss"])

    md = [
        "# Experiment: do ENSO and Indian Ocean Dipole indices add skill?",
        "",
        "_Generated by `python -m climrisk experiment`._",
        "",
        "ONI (ENSO) is used at the issue month; DMI (IOD) four months earlier, matching when each",
        "index is actually published. Everything else (splits, grids, seeds) is identical.",
        "",
        "## Validation 2016–2019 (used to decide)",
        "",
        "| Features | GB rainfall MAE (mm) | Ridge MAE (mm) | GB drought log-loss "
        "| Logistic log-loss |",
        "|---|---:|---:|---:|---:|",
        val_row(base_label, base),
        val_row(idx_label, idx),
        "",
        "## Test 2020 onward (reported only)",
        "",
        "| Features | GB rainfall skill [95% CI] | Ridge rainfall skill | GB drought vs ensemble "
        "| Logistic drought vs ensemble | 80% coverage |",
        "|---|---:|---:|---:|---:|---:|",
        test_row(base_label, base),
        test_row(idx_label, idx),
        "",
        "## Decision",
        "",
        f"On validation, the indices {'reduce' if helps_reg else 'do not reduce'} rainfall error "
        f"and {'improve' if helps_clf else 'do not improve'} drought log-loss for gradient "
        f"boosting. `USE_CLIMATE_INDICES` in `config.py` is set to match: "
        f"**{helps_reg and helps_clf}**.",
        "",
        "The decision is made on validation only. If the test period looks better with the",
        "indices, that is worth noting, but switching because of it would tune the model to the",
        "test set. 2020–2026 contained a triple-dip La Niña and a strong 2026 El Niño, so a",
        "longer independent period is needed before adopting them.",
        "",
    ]
    reports_dir.mkdir(parents=True, exist_ok=True)
    (reports_dir / "experiment_climate_indices.md").write_text("\n".join(md), encoding="utf-8")
    return {"helps_regression": helps_reg, "helps_drought": helps_clf}
