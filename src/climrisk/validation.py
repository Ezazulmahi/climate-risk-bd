"""Independent check of the ERA5 rainfall used by the city model against CHIRPS.

CHIRPS blends satellite estimates with rain-gauge records, so agreement with it
is evidence that ERA5's month-to-month variability (what anomalies and SPI
depend on) is real, even if absolute totals differ. BMD station data would be
the gold standard; CHIRPS is the best freely available proxy.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from . import config, plots
from .spi import spi

VALIDATION_PATH = config.PROCESSED_DIR / "era5_chirps_validation.json"


def chirps_at_points(chirps, cities: pd.DataFrame, radius: int = 1) -> pd.DataFrame:
    """Mean of the (2r+1)^2 CHIRPS cells around each city (~16 km box for r=1)."""
    months, lats, lons, data = chirps
    frames = []
    for c in cities.itertuples():
        iy, ix = np.abs(lats - c.lat).argmin(), np.abs(lons - c.lon).argmin()
        block = data[:, max(iy - radius, 0): iy + radius + 1, max(ix - radius, 0): ix + radius + 1]
        frames.append(pd.DataFrame({"city": c.city, "date": months,
                                    "chirps_mm": np.nanmean(block, axis=(1, 2))}))
    return pd.concat(frames, ignore_index=True)


def compare(clean_df: pd.DataFrame, chirps) -> pd.DataFrame:
    cities = clean_df.groupby("city")[["lat", "lon"]].first().reset_index()
    both = clean_df[["city", "date", "precip_mm"]].merge(
        chirps_at_points(chirps, cities), on=["city", "date"]
    ).dropna()
    rows = []
    for city, g in both.groupby("city"):
        g = g.set_index("date").sort_index()
        vals = g[["precip_mm", "chirps_mm"]]
        anom = vals - vals.groupby(vals.index.month).transform("mean")
        s_era = spi(g["precip_mm"], 3, config.REF_START, config.REF_END)
        s_chi = spi(g["chirps_mm"], 3, config.REF_START, config.REF_END)
        ok = s_era.notna() & s_chi.notna()
        d_era, d_chi = s_era[ok] <= -1, s_chi[ok] <= -1
        agree = float((d_era == d_chi).mean())
        p_e, p_c = d_era.mean(), d_chi.mean()
        chance = p_e * p_c + (1 - p_e) * (1 - p_c)
        rows.append({
            "city": city,
            "era5_over_chirps_total": g["precip_mm"].sum() / g["chirps_mm"].sum(),
            "monthly_corr": g["precip_mm"].corr(g["chirps_mm"]),
            "anomaly_corr": anom["precip_mm"].corr(anom["chirps_mm"]),
            "spi3_corr": s_era[ok].corr(s_chi[ok]),
            "drought_agreement": agree,
            "drought_kappa": (agree - chance) / (1 - chance),
        })
    return pd.DataFrame(rows), both


def write_report(clean_df: pd.DataFrame, chirps) -> pd.DataFrame:
    import matplotlib.pyplot as plt

    table, both = compare(clean_df, chirps)
    plots.apply_style()
    d = both[both["city"] == "Dhaka"].set_index("date")
    s_era = spi(d["precip_mm"], 3, config.REF_START, config.REF_END)
    s_chi = spi(d["chirps_mm"], 3, config.REF_START, config.REF_END)
    fig, ax = plt.subplots(figsize=(10, 3.6))
    recent = s_era.index >= "2010-01-01"
    ax.plot(s_chi.index[recent], s_chi[recent], color=plots.ORANGE, linewidth=1.5,
            label="CHIRPS (satellite + gauges)")
    ax.plot(s_era.index[recent], s_era[recent], color=plots.BLUE, linewidth=1.5,
            label="ERA5 (used by the city model)")
    ax.axhline(-1, color=plots.TEXT_SECONDARY, linewidth=0.8, linestyle="--")
    ax.set_ylabel("SPI-3")
    ax.set_title("Dhaka SPI-3: two independent rainfall datasets largely agree")
    ax.legend(loc="lower left", ncol=2)
    plots.save(fig, config.FIGURES_DIR / "validation_spi3_dhaka.png")

    md = [
        "# Is ERA5 rainfall trustworthy? A check against CHIRPS",
        "",
        "_Generated by `python -m climrisk districts`._",
        "",
        "CHIRPS v2.0 blends satellite estimates with rain-gauge records. Each city's ERA5 series",
        "is compared with the mean of the CHIRPS cells around it, over all months both cover.",
        "",
        "| City | ERA5 / CHIRPS total | Monthly corr. | Anomaly corr. | SPI-3 corr. "
        "| Drought-month agreement | Cohen's κ |",
        "|---|---:|---:|---:|---:|---:|---:|",
        *[
            f"| {r.city} | {r.era5_over_chirps_total:.2f} | {r.monthly_corr:.2f} | "
            f"{r.anomaly_corr:.2f} | {r.spi3_corr:.2f} | {r.drought_agreement:.0%} | "
            f"{r.drought_kappa:.2f} |"
            for r in table.itertuples()
        ],
        "",
        "How to read it: monthly correlation is inflated by the shared monsoon cycle. Anomaly",
        "and SPI-3 correlation measure agreement on *unusual* months, which is what the",
        "forecasts depend on. Cohen's κ corrects drought agreement for chance (0 = chance,",
        "1 = perfect; 0.4–0.6 is usually called moderate, above 0.6 substantial).",
        "",
        "![Dhaka SPI-3](figures/validation_spi3_dhaka.png)",
        "",
    ]
    (config.REPORTS_DIR / "data_validation_chirps.md").write_text("\n".join(md), encoding="utf-8")
    table.round(4).to_json(VALIDATION_PATH, orient="records", indent=2)
    return table
