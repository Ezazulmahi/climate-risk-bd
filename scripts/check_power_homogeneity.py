"""Why this project does not use NASA POWER precipitation.

Downloads POWER's monthly PRECTOTCORR for each city, compares annual totals with
the ERA5 data the pipeline uses, and saves a figure. Run after `climrisk ingest`:

    python scripts/check_power_homogeneity.py
"""

from __future__ import annotations

import matplotlib.pyplot as plt
import pandas as pd
import requests

from climrisk import config, plots

URL = "https://power.larc.nasa.gov/api/temporal/monthly/point"


def power_annual(city: config.City, end: int) -> pd.Series:
    resp = requests.get(
        URL,
        params={"parameters": "PRECTOTCORR", "community": "AG", "latitude": city.lat,
                "longitude": city.lon, "start": config.START_YEAR, "end": end, "format": "JSON"},
        timeout=120,
    )
    resp.raise_for_status()
    series = resp.json()["properties"]["parameter"]["PRECTOTCORR"]
    rows = []
    for key, mm_day in series.items():
        year, month = int(key[:4]), int(key[4:])
        if month == 13 or mm_day < 0:
            continue
        rows.append((year, mm_day * pd.Period(f"{year}-{month:02d}").days_in_month))
    df = pd.DataFrame(rows, columns=["year", "mm"])
    counts = df.groupby("year")["mm"].count()
    return df.groupby("year")["mm"].sum()[counts == 12]


def main() -> None:
    era5 = pd.read_csv(config.CLEAN_PATH)
    counts = era5.groupby(["city", "year"])["precip_mm"].count()
    era5_annual = era5.groupby(["city", "year"])["precip_mm"].sum()[counts == 12]
    end = int(era5["year"].max())

    rows = []
    plots.apply_style()
    fig, ax = plt.subplots(figsize=(9, 4.2))
    for city in config.CITIES:
        if city.name not in era5_annual.index.get_level_values("city"):
            continue
        p = power_annual(city, end)
        e = era5_annual.loc[city.name]
        ratio = (p / e).dropna()
        rows.append({
            "city": city.name,
            "power_over_era5_1981_1996": ratio.loc[:1996].mean(),
            "power_over_era5_2016_on": ratio.loc[2016:].mean(),
        })
        if city.name == "Dhaka":
            ax.plot(p.index, p.values, color=plots.ORANGE, label="NASA POWER (PRECTOTCORR)")
            ax.plot(e.index, e.values, color=plots.BLUE, label="ERA5 (used here)")
    ax.set_ylabel("Annual rainfall (mm)")
    ax.set_title("Dhaka: POWER precipitation has a step change; ERA5 does not")
    ax.legend(loc="upper left")
    plots.save(fig, config.FIGURES_DIR / "data_power_vs_era5.png")

    table = pd.DataFrame(rows).round(2)
    print(table.to_string(index=False))
    md = ["| City | POWER / ERA5, 1981-1996 | POWER / ERA5, 2016 on |", "|---|---:|---:|"]
    md += [f"| {r.city} | {r.power_over_era5_1981_1996:.2f} | {r.power_over_era5_2016_on:.2f} |"
           for r in table.itertuples()]
    (config.REPORTS_DIR / "data_source_check.md").write_text(
        "# NASA POWER vs ERA5 annual rainfall\n\n_Generated by "
        "`scripts/check_power_homogeneity.py`._\n\n" + "\n".join(md)
        + "\n\n![POWER vs ERA5](figures/data_power_vs_era5.png)\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
